// Skeleton generator: emitSkeleton(ast, existingSrc?) -> string for
// BO_Servers/class/<Service>.js.
//
// Each method takes a single destructured object and returns { msg, result }.
// Method bodies live inside // <sdl:keep method> / // </sdl:keep> markers so
// hand-written logic is recognizable and preservable.
//
// ADDITIVE-ONLY CONTRACT (default):
//   If `existingSrc` is provided (the target file already exists), the
//   generator NEVER rewrites the body of a method that already exists in the
//   file. It only appends methods that are newly declared in the SDL and
//   missing from the file. If every SDL method already exists, the existing
//   source is returned UNCHANGED, byte-for-byte. This is what protects the
//   real Criminal.js (full pg logic) from being clobbered.

import { classifyArity, typeToString } from './ast.js'

const BANNER = `// AUTO-GENERATED skeleton — safe to edit method bodies inside <sdl:keep> markers.
// Generated by tools/sdlc.js from the service's .sdl definition.
// Re-running the generator is ADDITIVE: existing methods are never rewritten.`

// SDL scalar type -> JSDoc/JS type. Unknown idents (domain types) map to Object.
const JSDOC_TYPES = {
  string: 'string',
  int: 'number',
  float: 'number',
  number: 'number',
  bool: 'boolean',
  boolean: 'boolean',
  json: 'Object',
  any: '*',
  void: 'void',
}

function jsType(type) {
  if (!type) return '*'
  const base = JSDOC_TYPES[type.name] ?? 'Object'
  return type.array ? `${base}[]` : base
}

/** JSDoc block for a BO method (params come destructured from a single object). */
function jsdoc(service, method) {
  const lines = [
    `  /**`,
    `   * ${method.name} — ${service.name} business object (BO implementation).`,
  ]
  if (method.params.length === 0) {
    lines.push(`   * @param {Object} [args]`)
  } else {
    lines.push(`   * @param {Object} args`)
    for (const p of method.params) {
      const name = p.type.optional ? `[args.${p.name}]` : `args.${p.name}`
      lines.push(`   * @param {${jsType(p.type)}} ${name}`)
    }
  }
  const result = method.returns ? `${jsType(method.returns)}|null` : '*'
  const label = typeToString(method.returns)
  lines.push(`   * @returns {Promise<{ msg: string, result: ${result} }>}${label ? ` ${label}` : ''}`)
  lines.push(`   */`)
  return lines.join('\n')
}

/** Destructured object signature for a method, e.g. `{ id, q } = {}`. */
function destructureSignature(method) {
  if (method.params.length === 0) return '{} = {}'
  const names = method.params.map((p) => p.name).join(', ')
  return `{ ${names} } = {}`
}

function emitMethod(service, method) {
  const sig = destructureSignature(method)
  const arity = classifyArity(method)
  return [
    jsdoc(service, method),
    `  async ${method.name}(${sig}) {`,
    `    // <sdl:keep ${method.name}>`,
    `    // TODO: implement ${method.name} (${arity} arity)`,
    `    return { msg: 'Not implemented: ${method.name}', result: null }`,
    `    // </sdl:keep>`,
    `  }`,
  ].join('\n')
}

function emitFresh(service) {
  const methods = service.methods.map((m) => emitMethod(service, m)).join('\n\n')
  return [
    BANNER,
    ``,
    `export class ${service.name} {`,
    methods,
    `}`,
    ``,
  ].join('\n')
}

/**
 * Detect whether a method named `name` is already declared in `src`.
 * Matches `async <name>(` allowing arbitrary leading whitespace.
 */
function methodExists(src, name) {
  const re = new RegExp(`async\\s+${escapeRe(name)}\\s*\\(`)
  return re.test(src)
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/**
 * Append missing methods to an existing class body, just before the final
 * closing brace. Returns the original source untouched if nothing is missing.
 */
function appendMissing(existingSrc, missingMethods, service) {
  if (missingMethods.length === 0) return existingSrc

  const block = missingMethods.map((m) => emitMethod(service, m)).join('\n\n')

  // Insert before the LAST closing brace of the file (the class terminator).
  const lastBrace = existingSrc.lastIndexOf('}')
  if (lastBrace === -1) {
    // No class brace found — fall back to appending at the end.
    return `${existingSrc}\n${block}\n`
  }

  const before = existingSrc.slice(0, lastBrace)
  const after = existingSrc.slice(lastBrace)
  // Ensure a blank line separates appended methods from prior content.
  const sep = before.endsWith('\n') ? '\n' : '\n\n'
  return `${before}${sep}${block}\n${after}`
}

export function emitSkeleton(ast, existingSrc) {
  if (!ast || !Array.isArray(ast.services) || ast.services.length === 0) {
    throw new Error('emitSkeleton(ast): AST has no services')
  }
  if (ast.services.length > 1) {
    throw new Error(
      'emitSkeleton(ast): expected a single service per skeleton file',
    )
  }
  const service = ast.services[0]

  // Fresh file: emit the full skeleton.
  if (existingSrc == null || existingSrc.trim() === '') {
    return emitFresh(service)
  }

  // Existing file: additive-only. Only append methods missing from the file.
  const missing = service.methods.filter(
    (m) => !methodExists(existingSrc, m.name),
  )
  return appendMissing(existingSrc, missing, service)
}
